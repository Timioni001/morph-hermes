/* Build dashboard/dist from dashboard/src.
 *
 * Deliberately not a bundler: the Hermes dashboard loads a plain IIFE and takes
 * React from its own SDK, so "building" is concatenating the sources in order and
 * copying the stylesheet. No node_modules, no lockfile, nothing to audit.
 *
 *   node scripts/build_dashboard.mjs [--check]
 *
 * --check verifies dist matches src (used by the tests and CI) instead of writing.
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "dashboard", "src");
const dist = join(root, "dashboard", "dist");
const check = process.argv.includes("--check");

const parts = readdirSync(src).filter((name) => name.endsWith(".js")).sort();
if (parts.length === 0) { throw new Error("no dashboard sources found"); }

const banner = "/* Generated by scripts/build_dashboard.mjs from dashboard/src/"
  + " — edit the sources, not this file. */\n";
const bundle = banner + parts.map((name) => readFileSync(join(src, name), "utf8")).join("");
const css = readFileSync(join(src, "style.css"), "utf8");

const targets = [[join(dist, "index.js"), bundle], [join(dist, "style.css"), css]];

if (check) {
  let ok = true;
  for (const [path, want] of targets) {
    let have = "";
    try { have = readFileSync(path, "utf8"); } catch { have = ""; }
    if (have !== want) {
      ok = false;
      console.error(`stale: ${path} differs from the sources`);
    }
  }
  if (!ok) {
    console.error("run: node scripts/build_dashboard.mjs");
    process.exit(1);
  }
  console.log(`dist is current (${parts.length} source file(s))`);
} else {
  mkdirSync(dist, { recursive: true });
  for (const [path, body] of targets) { writeFileSync(path, body, "utf8"); }
  console.log(`built dashboard/dist/index.js (${bundle.length} bytes) from ${parts.join(", ")}`);
}
